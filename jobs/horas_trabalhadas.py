from core.template import TemplateJob

class HorasTrabalhadasJob(TemplateJob):

    def __init__(self, engine):
        super().__init__(
            engine,
            "Horas-Trabalhadas",
            base_path=r"C:\Users\llima\Desktop\Relatorios"
        )
    def get_query(self):
        return f"""
SELECT DISTINCT
	RA_FILIAL AS 'FILIAL'
   ,(SELECT
			RJ_DESC
		FROM SRJ010
		WHERE RJ_FUNCAO = RA_CODFUNC)
	AS 'FUNÇÃO'
   ,(SELECT
			CASE
				WHEN RA_SITFOLH = '' THEN 'ATIVO'
				WHEN RA_SITFOLH = 'F' THEN 'FÉRIAS'
				WHEN RA_RESCRAI IN ('30', '31') THEN 'TRANSFERIDO'
				WHEN RA_SITFOLH = 'D' THEN 'DESLIGADO'
				WHEN RA_SITFOLH = 'A' THEN 'AFASTADO'
			END)
	AS 'SITUAÇÃO'
   , (SELECT CASE WHEN RA_CATFUNC = 'A' THEN 'AUTONOMO' ELSE 'NORMAL' END) AS 'TIPO'
   ,(SELECT
			CASE
				WHEN RA_CATFUNC = 'A' THEN 'AUTONOMO'
				WHEN RA_CATFUNC = 'C' THEN 'COMISSIONADO'
				WHEN RA_CATFUNC = 'D' THEN 'DIARISTA'
				WHEN RA_CATFUNC = 'E' THEN 'ESTAGIARIO MENSALISTA'
				WHEN RA_CATFUNC = 'G' THEN 'ESTAGIARIO HORISTA'
				WHEN RA_CATFUNC = 'H' THEN 'HORISTA'
				WHEN RA_CATFUNC = 'I' THEN 'PROFESSOR MENSALISTA'
				WHEN RA_CATFUNC = 'J' THEN 'PROFESSOR AULISTA'
				WHEN RA_CATFUNC = 'M' THEN 'MENSALISTA'
				WHEN RA_CATFUNC = 'P' THEN 'PRO-LABORE'
				WHEN RA_CATFUNC = 'S' THEN 'SEMANALISTA'
				WHEN RA_CATFUNC = 'T' THEN 'TAREFEIRO' 
			END)
	AS 'RECEBIMENTO'
	,MONTH(GETDATE()) AS 'PERIODO_MES'
	,YEAR(GETDATE()) AS 'PERIODO_ANO'
	,RA_HRSEMAN AS 'HORAS'
	,(SELECT TOP 1 CTT_DESC01 FROM CTT010 WHERE CTT_CUSTO = RA_CC) 'CENTRO_CUSTO'
FROM SRA010
WHERE D_E_L_E_T_ = '' and RA_DEMISSA = '' AND RA_MAT IN (SELECT TNY_MAT FROM TNY010 WHERE TNY_DTINIC >= CONVERT(VARCHAR, DATEADD(DAY, -1, GETDATE()), 112) AND TNY_DTINIC <= CONVERT(VARCHAR, GETDATE(), 112) AND D_E_L_E_T_ = '')
        """